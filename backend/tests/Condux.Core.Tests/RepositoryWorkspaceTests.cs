using Condux.Core.FixEngine;
using Condux.Core.SourceControl;
using Xunit;

namespace Condux.Core.Tests;

// The workspace an agentic run edits holds only the files fetched for the issue. These pin what it does
// about the rest of the repository: read it on demand, and refuse to replace a file the run has not seen
// whole, which is how a run once rewrote a test file it had not been shown and deleted every test in it.
public class RepositoryWorkspaceTests
{
    private const string Shown = "src/cart.ts";
    private const string Tests = "test/cart.test.ts";
    private const string Lockfile = "pnpm-lock.yaml";

    private static readonly Dictionary<string, RepoFile> Repository = new()
    {
        [Shown] = new(Shown, "export const items = [];", "cart-sha"),
        [Tests] = new(Tests, "it('totals', () => {}); it('empties', () => {});", "tests-sha"),
        // The host has it but, like GitHub over 1 MB, will not return its contents.
        [Lockfile] = new(Lockfile, null, "lock-sha"),
    };

    private sealed class Reader
    {
        public List<string> Fetches { get; } = [];

        public Exception? Fails { get; init; }

        public Task<RepoFile?> ReadAsync(string path, CancellationToken _)
        {
            Fetches.Add(path);
            return Fails is not null
                ? Task.FromException<RepoFile?>(Fails)
                : Task.FromResult(Repository.GetValueOrDefault(path));
        }
    }

    // The checkout is seeded like the gateway seeds it: the fetched file, plus anything a test plants to
    // stand for state a sandbox command left behind.
    private static RepositoryWorkspace Create(
        Reader reader, Dictionary<string, string>? planted = null, bool shownWhole = true)
    {
        var seed = new Dictionary<string, string> { [Shown] = Repository[Shown].Content! };
        foreach (var (path, contents) in planted ?? [])
        {
            seed[path] = contents;
        }
        return new RepositoryWorkspace(
            new InMemoryWorkspace(seed), [Repository[Shown]], shownWhole ? [Repository[Shown]] : [],
            reader.ReadAsync);
    }

    [Fact]
    public async Task Reads_a_file_the_checkout_lacks_from_the_repository()
    {
        var workspace = Create(new Reader());

        Assert.Equal(Repository[Tests].Content, await workspace.ReadFileAsync(Tests));
        Assert.True(workspace.Seen.Includes(Tests, "tests-sha"));
    }

    [Fact]
    public async Task Refuses_to_replace_an_existing_file_the_run_never_read()
    {
        var workspace = Create(new Reader());

        var refusal = await Assert.ThrowsAsync<InvalidOperationException>(
            () => workspace.WriteFileAsync(Tests, "it('new', () => {});"));

        Assert.Contains("read it first", refusal.Message, StringComparison.Ordinal);
        Assert.Empty(workspace.ChangedFiles);
        Assert.False(workspace.Seen.Includes(Tests, "tests-sha"));
    }

    [Fact]
    public async Task Replaces_an_existing_file_once_it_has_been_read()
    {
        var workspace = Create(new Reader());

        await workspace.ReadFileAsync(Tests);
        await workspace.WriteFileAsync(Tests, "it('totals', () => {}); it('new', () => {});");

        Assert.Contains(Tests, workspace.ChangedFiles.Keys);
    }

    [Fact]
    public async Task A_file_the_opening_message_carried_whole_needs_no_read()
    {
        var reader = new Reader();
        var workspace = Create(reader);

        await workspace.WriteFileAsync(Shown, "export const items = [] as Item[];");

        Assert.Contains(Shown, workspace.ChangedFiles.Keys);
        Assert.Empty(reader.Fetches);
    }

    // The opening message cuts a long file short, so it was not seen whole until the model reads it.
    [Fact]
    public async Task A_file_the_opening_message_cut_short_must_be_read_first()
    {
        var workspace = Create(new Reader(), shownWhole: false);

        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.WriteFileAsync(Shown, "changed"));

        await workspace.ReadFileAsync(Shown);
        await workspace.WriteFileAsync(Shown, "changed");
        Assert.True(workspace.Seen.Includes(Shown, "cart-sha"));
    }

    // In a sandbox a command can leave any text at a real file's path. Reading that is not reading the
    // repository's file, so it does not make the real one replaceable.
    [Fact]
    public async Task Text_a_command_left_at_a_repository_path_does_not_count_as_reading_it()
    {
        var workspace = Create(new Reader(), planted: new() { [Tests] = "generated by a command" });

        Assert.Equal("generated by a command", await workspace.ReadFileAsync(Tests));

        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.WriteFileAsync(Tests, "x"));
        Assert.False(workspace.Seen.Includes(Tests, "tests-sha"));
    }

    // The same for a file the run did fetch: once a command has changed it in the sandbox, reading it gives
    // the command's text, which is not the repository's file the opening message cut short.
    [Fact]
    public async Task A_fetched_file_a_command_has_changed_does_not_count_as_read()
    {
        var workspace = Create(new Reader(), planted: new() { [Shown] = "rewritten by a command" }, shownWhole: false);

        Assert.Equal("rewritten by a command", await workspace.ReadFileAsync(Shown));

        Assert.False(workspace.Seen.Includes(Shown, "cart-sha"));
        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.WriteFileAsync(Shown, "x"));
    }

    // The host compares the blob the run saw with the blob the file is now.
    [Fact]
    public async Task A_file_is_seen_as_the_blob_that_was_read_and_no_other()
    {
        var workspace = Create(new Reader());

        await workspace.ReadFileAsync(Tests);

        Assert.True(workspace.Seen.Includes(Tests, "tests-sha"));
        Assert.False(workspace.Seen.Includes(Tests, "changed-since"));
    }

    // Two spellings of one scoped path are one file, recorded once rather than failing the run.
    [Fact]
    public void Two_spellings_of_one_path_are_one_file_seen()
    {
        var seen = FilesSeen.Only([new RepoFile("src/cart.ts", "a", "sha-1"), new RepoFile("./src/cart.ts", "a", "sha-1")]);

        Assert.True(seen.Includes("src/cart.ts", "sha-1"));
    }

    [Fact]
    public async Task Creates_a_file_the_repository_does_not_have_and_asks_only_once()
    {
        var reader = new Reader();
        var workspace = Create(reader);

        await workspace.WriteFileAsync("test/new.test.ts", "it('new', () => {});");
        await workspace.WriteFileAsync("test/new.test.ts", "it('newer', () => {});");

        Assert.Equal("it('newer', () => {});", workspace.ChangedFiles["test/new.test.ts"]);
        Assert.Equal(["test/new.test.ts"], reader.Fetches);
    }

    [Fact]
    public async Task A_file_the_host_will_not_return_can_be_neither_read_nor_replaced()
    {
        var workspace = Create(new Reader());

        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.ReadFileAsync(Lockfile));
        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.WriteFileAsync(Lockfile, "lockfileVersion: 9"));

        Assert.False(workspace.Seen.Includes(Lockfile, "lock-sha"));
        Assert.Empty(workspace.ChangedFiles);
    }

    // A failed read is the model's to retry and a write that needed the answer is refused, both as tool
    // errors the loop hands back, rather than an exception that ends the run.
    [Fact]
    public async Task A_host_that_fails_to_answer_is_a_failed_tool_call_and_refuses_the_write()
    {
        var workspace = Create(new Reader { Fails = new HttpRequestException("503") });

        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.ReadFileAsync(Tests));
        await Assert.ThrowsAsync<InvalidOperationException>(() => workspace.WriteFileAsync(Tests, "x"));
        Assert.Empty(workspace.ChangedFiles);
    }

    [Fact]
    public async Task A_path_spelled_differently_is_the_same_file()
    {
        var workspace = Create(new Reader());

        await workspace.ReadFileAsync("./test/./cart.test.ts");

        await workspace.WriteFileAsync(Tests, "it('changed', () => {});");
        Assert.Contains(Tests, workspace.ChangedFiles.Keys);
    }

    // The loop hands the refusal back as a failed tool call rather than ending the run, so the agent can
    // read the file and try again, which is the recovery the refusal exists to prompt.
    [Fact]
    public async Task In_a_run_the_refusal_is_a_tool_error_the_agent_recovers_from()
    {
        var workspace = Create(new Reader());
        var write = new AgentToolCall("w1", AgentToolNames.WriteFile,
            new Dictionary<string, string> { ["path"] = Tests, ["contents"] = "it('new', () => {});" });
        var conversation = new Script(
            AgentTurn.Calls([write]),
            AgentTurn.Calls([new AgentToolCall("r1", AgentToolNames.ReadFile,
                new Dictionary<string, string> { ["path"] = Tests })]),
            AgentTurn.Calls([write with { Id = "w2" }]),
            AgentTurn.Calls([new AgentToolCall("f1", AgentToolNames.Finish,
                new Dictionary<string, string> { ["summary"] = "Add a test." })]));

        var result = await new AgentLoop(conversation, workspace).RunAsync();

        var refused = Assert.Single(conversation.Received[1]);
        Assert.True(refused.IsError);
        Assert.Contains("read it first", refused.Content, StringComparison.Ordinal);
        Assert.Contains(Tests, result.ChangedFiles.Keys);
    }

    private sealed class Script(params AgentTurn[] turns) : IAgentConversation
    {
        private int index;

        public List<IReadOnlyList<AgentToolResult>> Received { get; } = [];

        public Task<AgentTurn> NextAsync(
            IReadOnlyList<AgentToolResult> results, CancellationToken cancellationToken = default)
        {
            Received.Add(results);
            return Task.FromResult(turns[index++]);
        }
    }
}
